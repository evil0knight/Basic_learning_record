def title_of(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("# "):
                return line[2:].strip()
    return os.path.splitext(os.path.basename(path))[0]


def difficulty_of(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        txt = f.read(1200)
    m = re.search(r"难度：\s*(L[1-4][^\n]*)", txt)
    return m.group(1).strip() if m else "—"


def main() -> int:
    files = [f for f in os.listdir(ROOT) if f.endswith(".md") and f not in ("MOC.md", "模板.md")]
    stems = {os.path.splitext(f)[0] for f in files}
    assigned: dict[str, str] = {}
    for gname, members in GROUPS:
        for m in members:
            if m in stems and m not in assigned:
                assigned[m] = gname
    leftovers = sorted(stems - set(assigned))

    lines = [
        "# 行业",
        "",
        "[← MOC](../MOC.md) | [← 主页](../../index.md)",
        "",
        "---",
        "",
        f"共 {len(stems)} 个行业，按大类分组。新建时从 [模板](模板.md) 复制，然后重跑 "
        "`python .claude/scripts/build_industry_moc.py` 自动重建本索引。",
        "",
        "## 难度分级",
        "",
        "| 级别 | 特征 | 切入方法 |",
        "| ---- | ---- | -------- |",
        "| L1 直连经验 | 链条肉眼可见：餐饮、零售、电商 | 直接画钱流，重点找外行看不见的成本 |",
        "| L2 需要中间概念 | 保险、物流、SaaS、广告 | 先建术语表，词不通就不往下读 |",
        "| L3 有黑箱 | 半导体、医药、军工、大宗贸易 | 三问：谁付钱、谁承担风险、谁验收 |",
        "| L4 多学科加强监管 | 能源、医疗、金融衍生品 | 先拿教材或白皮书的目录当骨架 |",
        "",
    ]

    for gname, members in GROUPS:
        rows = [m for m in members if assigned.get(m) == gname]
        if not rows:
            continue
        lines += [f"## {gname}", "", "| 行业 | 难度 |", "| ---- | ---- |"]
        for m in sorted(rows):
            p = os.path.join(ROOT, m + ".md")
            lines.append(f"| [{title_of(p)}]({m}.md) | {difficulty_of(p)} |")
        lines.append("")

    if leftovers:
        lines += ["## 未归类", "", "| 行业 | 难度 |", "| ---- | ---- |"]
        for m in leftovers:
            p = os.path.join(ROOT, m + ".md")
            lines.append(f"| [{title_of(p)}]({m}.md) | {difficulty_of(p)} |")
        lines.append("")

    out = os.path.join(ROOT, "MOC.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"已生成 {out}")
    print(f"行业总数 {len(stems)}，已归类 {len(set(assigned) & stems)}，未归类 {len(leftovers)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
